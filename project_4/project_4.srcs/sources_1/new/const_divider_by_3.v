module const_divider_by_3 (
    input  [7:0] num,   // 8位被除数 (0 ~ 255)
    output [7:0] quo,   // 8位商
    output [7:0] rem    // 8位余数
);
    /* 
     * 【常数除法器优化算法：乘以倒数取高位法】
     * 目标：计算 num / 3
     * 核心思想：利用 num / 3 = num * (1/3)
     *          通过放大 2^9 倍 = 512 倍，
     *          (1/3) * 512 ≈ 170.66，向上取整为 171。
     *          所以 num / 3 ≈ (num * 171) >> 9
     * 
     * 这种方法将原本需要多周期或庞大组合逻辑的除法，
     * 降维打击成纯粹的加法和简单的移位，极大地节约了硬件资源！
     * 对于 8 位数 (最大255) 而言该逻辑精度完全无误差。
     */

    // 171 的二进制为 8'b10101011
    // 分解为 171 = 128 + 32 + 8 + 2 + 1
    // 所以 num * 171 = (num<<7) + (num<<5) + (num<<3) + (num<<1) + num
    wire [15:0] prod;
    
    assign prod = (num << 7) + 
                  (num << 5) + 
                  (num << 3) + 
                  (num << 1) + 
                  num;

    // 右移 9 位即提取 [15:9] 即可得到商
    assign quo = prod[15:9];

    // 余数 = 被除数 - 商 * 3
    // quo * 3 = (quo << 1) + quo
    assign rem = num - ((quo << 1) + quo);

endmodule
